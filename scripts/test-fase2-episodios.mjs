// Valida en Postgres real (PGlite) los patrones de escritura que usa la app
// con episodios tras la fase 2: cerrar (UPDATE estado+fecha_fin), reabrir
// (UPDATE estado='activo', fecha_fin=null) y su conflicto con el índice único
// de un solo episodio activo por paciente. (Los INSERT ya quedaron cubiertos
// por test-historial-medico.mjs.)
import { PGlite } from "@electric-sql/pglite";

const db = new PGlite();
const ok = [];
const fail = [];
function check(name, cond, extra = "") {
  (cond ? ok : fail).push(name);
  console.log(`${cond ? "✓" : "✗"} ${name}${extra ? " — " + extra : ""}`);
}
async function falla(nombre, sql) {
  try {
    await db.exec(sql);
    check(nombre, false, "NO fue rechazado");
  } catch (e) {
    check(nombre, /duplicate key|unique|violates|violación/i.test(e.message), e.message.split("\n")[0]);
  }
}

await db.exec(`
create table pacientes (paciente_id bigint generated by default as identity primary key, nombre_completo text);
create table episodios (
  id bigint generated always as identity primary key,
  paciente_id bigint not null references pacientes (paciente_id) on delete cascade,
  diagnostico text not null,
  sistema_afectado text,
  fecha_inicio date not null default current_date,
  fecha_fin date,
  estado text not null default 'activo' check (estado in ('activo','completado','abandonado')),
  notas text,
  created_at timestamptz not null default now(),
  constraint episodios_rango_valido check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint episodios_cierre_con_fecha check (estado = 'activo' or fecha_fin is not null)
);
create unique index episodios_un_activo_por_paciente on episodios (paciente_id) where estado = 'activo';
insert into pacientes (nombre_completo) values ('Ana');
-- Episodio 1: cerrado (abandonó en junio) · Episodio 2: activo desde ayer
insert into episodios (paciente_id, diagnostico, fecha_inicio, fecha_fin, estado)
values (1, 'Lumbalgia', '2026-06-01', '2026-06-20', 'abandonado'),
       (1, 'Lumbalgia', '2026-09-23', null, 'activo');
`);

// ── Cerrar (UPDATE como lo hace cerrarEpisodio) ──
await db.exec(`update episodios set estado = 'completado', fecha_fin = '2026-09-24' where id = 2;`);
const cerrado = (await db.query("select estado, fecha_fin from episodios where id = 2")).rows[0];
check("cerrarEpisodio: UPDATE estado+fecha_fin aplica (completado, 2026-09-24)",
  cerrado.estado === "completado" && new Date(cerrado.fecha_fin).toISOString().slice(0, 10) === "2026-09-24");

await falla("cerrar con fecha_fin < fecha_inicio es rechazado por el CHECK (rango)",
  `update episodios set fecha_fin = '2026-09-01' where id = 2`);
await falla("cerrar con fecha_fin null es rechazado por el CHECK (cierre con fecha)",
  `update episodios set fecha_fin = null where id = 2`);

// ── Reabrir (UPDATE como lo hace reabrirEpisodio) ──
await db.exec(`update episodios set estado = 'activo', fecha_fin = null where id = 2;`);
const reabierto = (await db.query("select estado, fecha_fin from episodios where id = 2")).rows[0];
check("reabrirEpisodio: UPDATE estado='activo', fecha_fin=null aplica",
  reabierto.estado === "activo" && reabierto.fecha_fin === null);

// ── Conflicto: reabrir el episodio 1 mientras el 2 está activo ──
await falla("reabrir un episodio habiendo otro activo → índice único lo rechaza",
  `update episodios set estado = 'activo', fecha_fin = null where id = 1`);

// ── Tras cerrar el activo, reabrir el viejo ya sí funciona ──
await db.exec(`update episodios set estado = 'abandonado', fecha_fin = '2026-09-24' where id = 2;`);
await db.exec(`update episodios set estado = 'activo', fecha_fin = null where id = 1;`);
const estados = (await db.query("select id, estado from episodios order by id")).rows;
check("cerrar el activo y reabrir el anterior: queda 1 activo (id=1) y 1 abandonado (id=2)",
  estados[0].estado === "activo" && estados[1].estado === "abandonado");

console.log(`\n${ok.length}/${ok.length + fail.length} validaciones OK`);
if (fail.length) { console.log("FALLARON:", fail); process.exit(1); }
