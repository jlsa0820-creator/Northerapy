// Valida download/historial_medico_northerapy.sql contra un esquema réplica
// del usuario y los escenarios de su caso de uso:
//   · paciente que termina su tratamiento (completado)
//   · paciente que corta sin terminar (abandonado)
//   · paciente que vuelve después de tiempo POR LO MISMO (nuevo episodio, mismo dx)
//   · paciente que vuelve POR OTRO PROBLEMA (nuevo episodio, otro dx)
//   · la app actual sigue escribiendo visitas sin enterarse de episodios
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";

const db = new PGlite();
const ok = [];
const fail = [];
function check(name, cond, extra = "") {
  (cond ? ok : fail).push(name);
  console.log(`${cond ? "✓" : "✗"} ${name}${extra ? " — " + extra : ""}`);
}
// PGlite devuelve las columnas date como objeto Date → normalizar a 'YYYY-MM-DD'
const f = (d) => (d == null ? null : d instanceof Date ? d.toISOString().slice(0, 10) : String(d).slice(0, 10));
async function falla(nombre, sql) {
  try {
    await db.exec(sql);
    check(nombre, false, "NO fue rechazado");
  } catch (e) {
    check(nombre, /duplicate key|unique|violates|violación/i.test(e.message), e.message.split("\n")[0]);
  }
}

// ── Esquema réplica (mismas columnas que toca el script; identity como el usuario) ──
await db.exec(`
create role authenticated;
create table pacientes (
  paciente_id bigint generated by default as identity primary key,
  nombre_completo text, diagnostico text, sistema_afectado text,
  primera_sesion date, sesiones_programadas int, sesiones_totales int default 0,
  status text, grupo_edad text, edad_valor int, edad_unidad text, sexo text,
  celular_principal text, como_nos_conocio text
);
create table asistencias (
  id bigint generated always as identity primary key,
  paciente_id bigint references pacientes(paciente_id),
  ultima_asistencia date, ses_totales int, ses_programadas int,
  pct_adherencia numeric, dias_sin_asistir int, frec_semanal numeric, status text
);
create table ingresos (
  id bigint generated always as identity primary key,
  paciente_id bigint references pacientes(paciente_id),
  fecha date, zonas int,
  terapia_estado text, terapia_monto numeric,
  diclofenaco_estado text, diclofenaco_monto numeric,
  ortopedico_estado text, ortopedico_monto numeric,
  total numeric,
  tipo text check (tipo is null or tipo in ('sesion','compra_paquete','venta_producto'))
);
`);

// ── Datos semilla: 4 pacientes representativos del estado actual ──
await db.exec(`
insert into pacientes (nombre_completo, diagnostico, sistema_afectado, primera_sesion, status) values
  ('Ana Activa',    'Lumbalgia',  'Musculoesquelético', '2026-08-01', 'Activo'),
  ('Beto Completó', 'Tendinitis', 'Musculoesquelético', '2026-05-04', 'Completó tratamiento'),
  ('Carla Cortó',   'Cervicalgia','Musculoesquelético', '2026-03-02', 'Abandonó'),
  ('Dani Sin Dx',    null,         null,                 '2026-07-10', 'Activo');

-- Sesiones reales de cada uno (filas tipo 'sesion' como las escribe la app)
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto, total, tipo) values
  ((select paciente_id from pacientes where nombre_completo='Ana Activa'),     '2026-08-01', 1, 'efectivo', 35, 35, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Ana Activa'),     '2026-08-08', 1, 'cubierta', 0,   0, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Beto Completó'),  '2026-05-04', 2, 'efectivo', 60, 60, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Beto Completó'),  '2026-05-11', 2, 'cubierta', 0,   0, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Beto Completó'),  '2026-05-18', 2, 'cubierta', 0,   0, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Beto Completó'),  '2026-05-25', 2, 'cubierta', 0,   0, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Carla Cortó'),    '2026-03-02', 1, 'efectivo', 35, 35, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Carla Cortó'),    '2026-03-09', 1, 'yape',     35, 35, 'sesion'),
  ((select paciente_id from pacientes where nombre_completo='Dani Sin Dx'),    '2026-07-10', 1, 'efectivo', 35, 35, 'sesion');
`);

// ── Ejecutar el script completo, tal cual lo ejecutará el usuario ──
const sql = readFileSync("/home/z/my-project/download/historial_medico_northerapy.sql", "utf8");
try {
  await db.exec(sql);
  check("El script ejecuta completo (tabla + RLS + índices + backfill + vista + verificación)", true);
} catch (e) {
  check("El script ejecuta completo (tabla + RLS + índices + backfill + vista + verificación)", false, e.message.split("\n")[0]);
}

// ── Backfill: 1 episodio por paciente con diagnóstico, estado derivado ──
const eps = (await db.query("select * from episodios order by id")).rows;
check("Backfill: 3 episodios (solo pacientes con diagnóstico; Dani Sin Dx queda fuera)", eps.length === 3, `creados: ${eps.length}`);
const ana = eps.find((e) => e.paciente_id === 1), beto = eps.find((e) => e.paciente_id === 2), carla = eps.find((e) => e.paciente_id === 3);
check("Ana (Activo) → episodio activo, sin fecha_fin, con su diagnóstico y sistema",
  ana && ana.estado === "activo" && ana.fecha_fin === null && ana.diagnostico === "Lumbalgia" && ana.sistema_afectado === "Musculoesquelético");
check("Beto (Completó tratamiento) → episodio completado con fecha_fin = última sesión (2026-05-25)",
  beto && beto.estado === "completado" && f(beto.fecha_fin) === "2026-05-25");
check("Carla (Abandonó) → episodio abandonado con fecha_fin = última sesión (2026-03-09)",
  carla && carla.estado === "abandonado" && f(carla.fecha_fin) === "2026-03-09");

// ── Idempotencia: re-ejecutar no duplica ni falla ──
try {
  await db.exec(sql);
  const n = (await db.query("select count(*)::int as n from episodios")).rows[0].n;
  check("Idempotencia: re-ejecutar el script entero no duplica episodios", n === 3, `episodios: ${n}`);
} catch (e) {
  check("Idempotencia: re-ejecutar el script entero no duplica episodios", false, e.message.split("\n")[0]);
}

// ── Integridad protegida por la BD ──
await falla("Regla: un paciente no puede tener 2 episodios activos (índice único parcial)",
  `insert into episodios (paciente_id, diagnostico) values (1, 'Otra cosa')`);
await falla("CHECK: estado fuera de vocabulario rechazado",
  `insert into episodios (paciente_id, diagnostico, estado) values (1, 'X', 'pendiente')`);
await falla("CHECK: fecha_fin menor que fecha_inicio rechazada",
  `insert into episodios (paciente_id, diagnostico, fecha_inicio, fecha_fin, estado) values (1, 'X', '2026-09-10', '2026-09-01', 'completado')`);
await falla("CHECK: episodio cerrado sin fecha_fin rechazado",
  `insert into episodios (paciente_id, diagnostico, estado) values (1, 'X', 'completado')`);
await falla("FK: episodio de un paciente inexistente rechazado",
  `insert into episodios (paciente_id, diagnostico) values (9999, 'X')`);

// ── Escenario 1: Ana vuelve después de tiempo POR LO MISMO ──
await db.exec(`
-- Ana terminó su tratamiento de lumbalgia (cierra episodio 1)…
update episodios set estado = 'completado', fecha_fin = '2026-08-08' where paciente_id = 1 and estado = 'activo';
-- …y vuelve el 15-sep por la misma lumbalgia (nuevo episodio)
insert into episodios (paciente_id, diagnostico, sistema_afectado, fecha_inicio) values (1, 'Lumbalgia', 'Musculoesquelético', '2026-09-15');
-- La app registra su visita de hoy SIN enterarse de episodios (flujo actual intacto)
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto, total, tipo)
values (1, '2026-09-15', 1, 'efectivo', 35, 35, 'sesion');
`);
const histAna = (await db.query("select * from episodios_v where paciente_id = 1 order by fecha_inicio")).rows;
check("Ana: el historial muestra 2 episodios (antes 1)", histAna.length === 2, `episodios: ${histAna.length}`);
check("   · episodio 1 (jun-ago): completado, 2 sesiones (las de agosto, no las nuevas)",
  histAna[0].estado === "completado" && Number(histAna[0].sesiones) === 2 && f(histAna[0].ultima_sesion) === "2026-08-08");
check("   · episodio 2 (15-sep): activo, mismo diagnóstico, 1 sesión (solo la de su retorno)",
  histAna[1].estado === "activo" && histAna[1].diagnostico === "Lumbalgia" && Number(histAna[1].sesiones) === 1 && f(histAna[1].ultima_sesion) === "2026-09-15");

// ── Escenario 2: Carla (que abandonó) vuelve POR OTRO PROBLEMA ──
await db.exec(`
insert into episodios (paciente_id, diagnostico, sistema_afectado, fecha_inicio) values (3, 'Lumbalgia', 'Musculoesquelético', '2026-09-16');
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto, total, tipo)
values (3, '2026-09-16', 1, 'efectivo', 35, 35, 'sesion');
`);
const histCarla = (await db.query("select diagnostico, estado from episodios_v where paciente_id = 3 order by fecha_inicio")).rows;
check("Carla: antecedentes con 2 diagnósticos distintos (cervicalgia abandonado + lumbalgia activo)",
  histCarla.length === 2 && histCarla[0].diagnostico === "Cervicalgia" && histCarla[0].estado === "abandonado"
  && histCarla[1].diagnostico === "Lumbalgia" && histCarla[1].estado === "activo");

// ── Escenario 3: episodio activo cuenta también sesiones posteriores (rango abierto) ──
await db.exec(`insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto, total, tipo)
values (3, '2026-09-19', 1, 'cubierta', 0, 0, 'sesion');`);
const carlaHoy = (await db.query("select sesiones from episodios_v where paciente_id = 3 and estado = 'activo'")).rows[0];
check("El episodio activo (sin fecha_fin) acumula las sesiones nuevas: 2", Number(carlaHoy.sesiones) === 2);

// ── La vista respetará el RLS de la API (security_invoker) ──
const vista = (await db.query("select reloptions from pg_class where relname = 'episodios_v'")).rows[0];
check("Vista episodios_v creada con security_invoker (respeta RLS vía API)",
  vista && vista.reloptions.includes("security_invoker=true"));

// ── Borrar paciente arrastra su historial (ON DELETE CASCADE) ──
await db.exec(`delete from ingresos where paciente_id = 2; delete from pacientes where paciente_id = 2;`);
const betoEps = (await db.query("select count(*)::int as n from episodios where paciente_id = 2")).rows[0].n;
check("Borrar un paciente borra también sus episodios (cascade)", betoEps === 0);

// ── La app actual sigue escribiendo igual (sin tocar episodios) ──
await db.exec(`
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto, diclofenaco_estado, diclofenaco_monto, ortopedico_estado, ortopedico_monto, total, tipo)
values (1, '2026-09-20', 1, 'yape', 35, 'efectivo', 6, 'no_aplica', 0, 41, 'sesion');
`);
const anaHoy = (await db.query("select sesiones from episodios_v where paciente_id = 1 and estado = 'activo'")).rows[0];
check("Escritura estilo app actual intacta: nueva visita (S/41) contada en su episodio activo",
  Number(anaHoy.sesiones) === 2);

console.log(`\n${ok.length}/${ok.length + fail.length} validaciones OK`);
if (fail.length) { console.log("FALLARON:", fail); process.exit(1); }
