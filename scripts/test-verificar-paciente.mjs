// Valida download/verificar_paciente.sql contra un esquema réplica del usuario
// y el flujo real: nuevo paciente + visita (sesión cubierta) + compra de paquete S/150.
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";

const db = new PGlite();
const ok = [];
const fail = [];
function check(name, cond, extra = "") {
  (cond ? ok : fail).push(name);
  console.log(`${cond ? "✓" : "✗"} ${name}${extra ? " — " + extra : ""}`);
}

// ── Esquema réplica (columnas que toca el script; ingresos ALWAYS identity + tipo como el usuario) ──
await db.exec(`
create table pacientes (
  paciente_id bigint generated by default as identity primary key,
  nombre_completo text, diagnostico text, primera_sesion date,
  sesiones_totales int default 0, sesiones_programadas int, status text,
  grupo_edad text, edad_valor int, edad_unidad text, sexo text,
  celular_principal text, como_nos_conocio text
);
create table asistencias (
  id bigint generated always as identity primary key,
  paciente_id bigint references pacientes(paciente_id),
  ultima_asistencia date, ses_totales int, ses_programadas int,
  pct_adherencia numeric, dias_sin_asistir int, frec_semanal numeric, status text
);
create table ingresos (
  id bigint generated always as identity primary key,
  paciente_id bigint references pacientes(paciente_id),
  fecha date, zonas int,
  terapia_estado text, terapia_monto numeric,
  diclofenaco_estado text, diclofenaco_monto numeric,
  ortopedico_estado text, ortopedico_monto numeric,
  total numeric,
  tipo text check (tipo is null or tipo in ('sesion','compra_paquete','venta_producto'))
);
`);

// ── Flujo del usuario: alta + compra paquete + visita cubierta ──
await db.exec(`
insert into pacientes (nombre_completo, diagnostico, primera_sesion, sesiones_totales, status)
values ('Paciente Ejemplo', 'Prueba', current_date, 1, 'Activo');

-- 1a. Compra del paquete (como hace la app: se inserta PRIMERO)
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto,
  diclofenaco_estado, diclofenaco_monto, ortopedico_estado, ortopedico_monto, total, tipo)
values ((select paciente_id from pacientes where nombre_completo = 'Paciente Ejemplo'),
  current_date, 0, 'efectivo', 150, 'no_aplica', 0, 'no_aplica', 0, 150, 'compra_paquete');

-- 1b. Visita del día (sesión cubierta por el paquete → S/0)
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto,
  diclofenaco_estado, diclofenaco_monto, ortopedico_estado, ortopedico_monto, total, tipo)
values ((select paciente_id from pacientes where nombre_completo = 'Paciente Ejemplo'),
  current_date, 1, 'cubierta', 0, 'no_aplica', 0, 'no_aplica', 0, 0, 'sesion');

insert into asistencias (paciente_id, ultima_asistencia, ses_totales, dias_sin_asistir, frec_semanal, status)
values ((select paciente_id from pacientes where nombre_completo = 'Paciente Ejemplo'),
  current_date, 1, 0, 1, 'Activo');
`);

// ── Ejecutar el script de verificación (tal cual el archivo) ──
const sql = readFileSync("/home/z/my-project/download/verificar_paciente.sql", "utf8");
// Extraer cada sentencia (select/with … ;) — los comentarios quedan fuera
const extraer = (texto) =>
  [...texto.matchAll(/(?:^|\n)\s*((?:with|select)\b[\s\S]*?;)/gi)].map((m) => m[1].trim());
const sentencias = extraer(sql);

check("El script se descompone en 4 sentencias ejecutables", sentencias.length === 4, `encontradas: ${sentencias.length}`);

const res1 = await db.query(sentencias[0]);
check("1) SELECT pacientes corre y encuentra 1 fila", res1.rows.length === 1 && res1.rows[0].nombre_completo === "Paciente Ejemplo");

const res2 = await db.query(sentencias[1]);
const compra = res2.rows.find((r) => Number(r.terapia_monto) === 150);
const visita = res2.rows.find((r) => Number(r.zonas) > 0);
check("2) SELECT ingresos corre y devuelve 2 filas", res2.rows.length === 2);
check("   · fila de compra: zonas=0, monto=150, tipo=compra_paquete",
  compra && Number(compra.zonas) === 0 && compra.tipo === "compra_paquete");
check("   · fila de visita: zonas=1, monto=0, estado=cubierta, tipo=sesion",
  visita && Number(visita.zonas) === 1 && Number(visita.terapia_monto) === 0 && visita.terapia_estado === "cubierta" && visita.tipo === "sesion");

const res3 = await db.query(sentencias[2]);
check("3) SELECT asistencias corre y devuelve 1 fila con ses_totales=1",
  res3.rows.length === 1 && Number(res3.rows[0].ses_totales) === 1);

const res4 = await db.query(sentencias[3]);
const r = res4.rows[0];
check("4) Resumen: paciente_existe=1", Number(r.paciente_existe) === 1);
check("   · filas_ingresos=2", Number(r.filas_ingresos) === 2);
check("   · sesiones_cubiertas=1", Number(r.sesiones_cubiertas) === 1);
check("   · sesiones_restantes=4 (quedan 4 de 5)", Number(r.sesiones_restantes) === 4);
check("   · deuda_total=0 (pagó todo)", Number(r.deuda_total) === 0);

// ── Caso alternativo: visita cobrada aparte (suelta S/35) + deuda pendiente ──
await db.exec(`
insert into ingresos (paciente_id, fecha, zonas, terapia_estado, terapia_monto,
  diclofenaco_estado, diclofenaco_monto, ortopedico_estado, ortopedico_monto, total, tipo)
values ((select paciente_id from pacientes where nombre_completo = 'Paciente Ejemplo'),
  current_date, 1, 'debe', 35, 'no_aplica', 0, 'no_aplica', 0, 35, 'sesion');
`);
const res5 = await db.query(sentencias[3]);
const r5 = res5.rows[0];
check("Caso suelta+debe: filas_ingresos=3", Number(r5.filas_ingresos) === 3);
check("   · sesiones_cubiertas sigue 1 (la de S/0)", Number(r5.sesiones_cubiertas) === 1);
check("   · deuda_total=35 (la línea en «debe»)", Number(r5.deuda_total) === 35);

// ── Caso paciente inexistente (nombre distinto) ──
const sqlAlt = sql.replaceAll("paciente ejemplo", "nombre que no existe");
const sAlt = extraer(sqlAlt);
const rA = (await db.query(sAlt[0])).rows;
const rB = (await db.query(sAlt[3])).rows[0];
check("Paciente inexistente: 0 filas y resumen en 0 (sin errores)", rA.length === 0 && Number(rB.paciente_existe) === 0 && Number(rB.deuda_total) === 0);

console.log(`\n${ok.length}/${ok.length + fail.length} validaciones OK`);
if (fail.length) { console.log("FALLARON:", fail); process.exit(1); }
